#!/usr/bin/env python3
"""Bundle the repository's pinned astronomy code for JavaScriptCore. No npm/build step for the site."""
from pathlib import Path
import re
ROOT = Path(__file__).resolve().parents[2]
base = ROOT / 'assets/vendor/satellite'
modules = {}
def add(path):
    path = path.resolve()
    key = path.relative_to(base).as_posix()
    if key in modules: return key
    source = path.read_text()
    modules[key] = ''
    def replace(match):
        names, relative = match.groups()
        dependency = add(path.parent / relative)
        return f'const {{{names}}} = require("{dependency}");'
    source = re.sub(r"import\s*\{([^}]+)\}\s*from\s*'([^']+)';", replace, source)
    exports = re.findall(r'export (?:function|const|var|let|class) (\w+)', source)
    source = re.sub(r'export (?=function|const|var|let|class)', '', source)
    if re.search(r'\b(import|export)\s', source): raise ValueError(f'Unsupported syntax in {key}')
    modules[key] = source + '\nreturn {' + ','.join(exports) + '};'
    return key
entries = ['io.js','ext.js','propagation/propagate.js','propagation/gstime.js','transforms.js','sun.js','shadow.js']
for entry in entries: add(base / entry)
parts = ['// Generated by ios/scripts/bundle_engine.py; source libraries remain in assets/vendor.\nvar window = this;']
parts.append((ROOT/'assets/vendor/astronomy/astronomy.browser.min.js').read_text())
parts.append((ROOT/'assets/vendor/suncalc/suncalc.js').read_text())
parts.append('var satellite = (function(){ const modules = {')
parts += ['"'+key+'": function(require){\n'+source+'\n},' for key,source in modules.items()]
parts.append('}; const cache = {}; function require(id){ return cache[id] || (cache[id] = modules[id](require)); } return Object.assign({},'+','.join(f'require("{e}")' for e in entries)+'); })();')
parts.append((ROOT/'assets/js/data/catalogs.js').read_text().replace('export const ', 'const '))
parts.append((ROOT/'ios/SkyCore/engine.js').read_text())
(ROOT/'ios/Resources/SkyEngine.js').write_text('\n'.join(parts))
print('Bundled pinned astronomy, SunCalc, SGP4 and sky engine')
